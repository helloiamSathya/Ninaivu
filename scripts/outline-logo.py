#!/usr/bin/env python3
"""Turn a font's glyphs for a word into SVG path data for the animated splash logo.

Usage: python3 scripts/outline-logo.py <font.ttf> [text] [--wght 400]
Writes src/logo/logoPaths.ts. Re-run with the real Gotti VF font to replace the stand-in.
"""
import sys, pathlib
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

args = [a for a in sys.argv[1:] if not a.startswith('--')]
font_path = args[0]
text = args[1] if len(args) > 1 else 'Ninaivu'
wght = None
if '--wght' in sys.argv:
    wght = float(sys.argv[sys.argv.index('--wght') + 1])

font = TTFont(font_path)
if 'fvar' in font and wght is not None:
    font = instantiateVariableFont(font, {'wght': wght})
gs = font.getGlyphSet()
cmap = font.getBestCmap()
upm = font['head'].unitsPerEm

x = 0
glyphs = []
ymin, ymax = 0, 0
for ch in text:
    name = cmap[ord(ch)]
    g = gs[name]
    bp = BoundsPen(gs); g.draw(bp)
    if bp.bounds:
        ymin = min(ymin, bp.bounds[1]); ymax = max(ymax, bp.bounds[3])
    glyphs.append((ch, name, x))
    x += g.width
total_w = x
height = ymax - ymin
scale = 100.0 / height  # normalise to 100 units tall

paths = []
for ch, name, ox in glyphs:
    pen = SVGPathPen(gs, ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
    # flip y, shift so the top of the tallest glyph is y=0
    tp = TransformPen(pen, (scale, 0, 0, -scale, ox * scale, ymax * scale))
    gs[name].draw(tp)
    d = pen.getCommands()
    if d:
        paths.append({'char': ch, 'd': d})

out = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'logo' / 'logoPaths.ts'
lines = ["// Generated by scripts/outline-logo.py. Do not edit by hand.",
         f"export const LOGO_VIEWBOX = {{ width: {total_w*scale:.2f}, height: 100 }};",
         "export const LOGO_PATHS: { char: string; d: string }[] = ["]
for p in paths:
    lines.append("  { char: %r, d: %r }," % (p['char'], p['d']))
lines.append("];")
out.write_text("\n".join(lines) + "\n")
print('wrote', out, 'width', round(total_w*scale,1), 'glyphs', len(paths))
